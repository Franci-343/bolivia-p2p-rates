-- ----------------------------------------------------------------------------
-- 1. Tabla de Control de Eventos Procesados (Garantia de Idempotencia Remota)
-- ----------------------------------------------------------------------------
-- Absorbe de forma determinista cualquier reintento tras caidas de red o cortes
-- que ocurran entre el COMMIT en Oracle y el ACK en SQLite local.
CREATE TABLE PROCESSED_EVENTS (
    EVENT_ID VARCHAR2(160) NOT NULL,
    EVENT_TYPE VARCHAR2(40) NOT NULL,
    APPLIED_AT TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT PK_PROCESSED_EVENTS PRIMARY KEY (EVENT_ID)
);

-- ----------------------------------------------------------------------------
-- 2. Tabla Central de Snapshots Historicos de Cotizaciones P2P
-- ----------------------------------------------------------------------------
-- Preserva el historial a largo plazo con precision matematica exacta NUMBER(24, 8)
-- para los campos BigDecimal de compra y venta.
CREATE TABLE RATE_SNAPSHOTS (
    ID NUMBER GENERATED BY DEFAULT AS IDENTITY,
    SOURCE_INSTANCE_ID VARCHAR2(64) NOT NULL,
    LOCAL_SNAPSHOT_ID NUMBER(12) NOT NULL,
    CYCLE_ID NUMBER(12) NOT NULL,
    CAPTURED_AT TIMESTAMP WITH TIME ZONE NOT NULL,
    DURATION_MS NUMBER(10) NOT NULL,
    IS_STALE NUMBER(1) DEFAULT 0 NOT NULL CHECK (IS_STALE IN (0, 1)),
    STATUS VARCHAR2(20) NOT NULL,
    FIAT VARCHAR2(10) DEFAULT 'BOB' NOT NULL,
    ASSET VARCHAR2(10) DEFAULT 'USDT' NOT NULL,

    -- Mercado de COMPRA (BOB -> USDT) con NUMBER(24, 8) para maxima precision BigDecimal
    BUY_REFERENCE_PRICE NUMBER(24, 8) DEFAULT 0 NOT NULL,
    BUY_AVERAGE_PRICE NUMBER(24, 8) DEFAULT 0 NOT NULL,
    BUY_MEDIAN_PRICE NUMBER(24, 8) DEFAULT 0 NOT NULL,
    BUY_MIN_PRICE NUMBER(24, 8) DEFAULT 0 NOT NULL,
    BUY_MAX_PRICE NUMBER(24, 8) DEFAULT 0 NOT NULL,
    BUY_VALID_COUNT NUMBER(6) DEFAULT 0 NOT NULL,
    BUY_DISCARDED_COUNT NUMBER(6) DEFAULT 0 NOT NULL,
    BUY_TOTAL_RECEIVED NUMBER(6) DEFAULT 0 NOT NULL,
    BUY_DETAILS_JSON CLOB CHECK (BUY_DETAILS_JSON IS JSON),

    -- Mercado de VENTA (USDT -> BOB)
    SELL_REFERENCE_PRICE NUMBER(24, 8) DEFAULT 0 NOT NULL,
    SELL_AVERAGE_PRICE NUMBER(24, 8) DEFAULT 0 NOT NULL,
    SELL_MEDIAN_PRICE NUMBER(24, 8) DEFAULT 0 NOT NULL,
    SELL_MIN_PRICE NUMBER(24, 8) DEFAULT 0 NOT NULL,
    SELL_MAX_PRICE NUMBER(24, 8) DEFAULT 0 NOT NULL,
    SELL_VALID_COUNT NUMBER(6) DEFAULT 0 NOT NULL,
    SELL_DISCARDED_COUNT NUMBER(6) DEFAULT 0 NOT NULL,
    SELL_TOTAL_RECEIVED NUMBER(6) DEFAULT 0 NOT NULL,
    SELL_DETAILS_JSON CLOB CHECK (SELL_DETAILS_JSON IS JSON),

    SYNCED_AT TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,

    CONSTRAINT PK_RATE_SNAPSHOTS PRIMARY KEY (ID),
    CONSTRAINT UK_SNAPSHOT_SOURCE_LOCAL UNIQUE (SOURCE_INSTANCE_ID, LOCAL_SNAPSHOT_ID)
);

-- Indices para consultas analiticas e historicas en Oracle
CREATE INDEX IDX_ORA_SNAP_CAPTURED_AT ON RATE_SNAPSHOTS(CAPTURED_AT DESC);
CREATE INDEX IDX_ORA_SNAP_CYCLE_ID ON RATE_SNAPSHOTS(CYCLE_ID DESC);

-- ----------------------------------------------------------------------------
-- 3. Tabla Replica de Clientes API (Auditoria y Control Centralizado)
-- ----------------------------------------------------------------------------
-- Solo almacena metadatos y hashes SHA-256 de API Keys (jamas llaves en plano).
CREATE TABLE API_CLIENTS (
    ID NUMBER GENERATED BY DEFAULT AS IDENTITY,
    CLIENT_ID VARCHAR2(64) NOT NULL,
    CLIENT_NAME VARCHAR2(128) NOT NULL,
    API_KEY_HASH VARCHAR2(64) NOT NULL,
    ROLE VARCHAR2(20) DEFAULT 'CONSUMER' NOT NULL,
    RATE_LIMIT_RPM NUMBER(6) DEFAULT 60 NOT NULL,
    IS_ACTIVE NUMBER(1) DEFAULT 1 NOT NULL CHECK (IS_ACTIVE IN (0, 1)),
    CREATED_AT TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
    UPDATED_AT TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
    DELETED_AT TIMESTAMP WITH TIME ZONE DEFAULT NULL,

    CONSTRAINT PK_API_CLIENTS PRIMARY KEY (ID),
    CONSTRAINT UK_API_CLIENTS_CLIENT_ID UNIQUE (CLIENT_ID)
);

CREATE INDEX IDX_ORA_CLIENT_HASH ON API_CLIENTS(API_KEY_HASH);

